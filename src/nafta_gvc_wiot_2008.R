calculate_variables = function(k, s, ind, F, D, B) {
  # Create vector H based on final demand for the country k
  H = matrix(0, nrow = ind, ncol = 1)
  for (i in (s*k-(s-1)): (s*k)) {
    H[i] = F[i]
  }
  
  # Calculate value added generated in all countries because of country k's consumption
  V_A = D %*% B %*% as.vector(H)
  V_A[is.na(V_A)] = 0
  
  # Calculate final output value added (FINO)
  FINO = sum(V_A)
  
  # Construct a vector vak to save the value added from different countries generated by country k
  vak = matrix(0, nrow = 44, ncol = 1)
  for (j in 1:44) {
    va = matrix(0, nrow = ind, ncol = 1)
    for (i in (s*j-(s-1)) : (s*j)) {
      va[i] = V_A[i]
    }
    vak[j] = sum(va)
  }
  
  # Calculate domestic value added outside the country k
  DVA = vak[k]
  
  # Calculate all value added outside the country k
  FVA = FINO - DVA
  
  # Calculate the share of all value added from different countries
  FVAS = vak / FINO
  
  # Calculate total share of foreign value added
  TFVAS = FVA / FINO
  
  # Calculate total share of domestic value added
  DVAS = DVA / FINO
  
  # Package all variables into a list and return
  return(list(
    FINO_2008 = FINO,
    vak_2008 = vak,
    DVA_2008 = DVA,
    FVA_2008 = FVA,
    FVAS_2008 = FVAS,
    TFVAS_2008 = TFVAS,
    DVAS_2008 = DVAS
  ))
}

